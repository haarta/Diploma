def find_index(paragraphs, expected_text):
    for index, paragraph in enumerate(paragraphs):
        if paragraph.text.strip() == expected_text:
            return index
    raise RuntimeError(f"Paragraph not found: {expected_text}")


def delete_paragraph(paragraph):
    element = paragraph._element
    parent = element.getparent()
    parent.remove(element)
    paragraph._element = None
    paragraph._p = None


def insert_paragraph_before(anchor, text="", style=None, alignment=None, bold=None):
    paragraph = anchor.insert_paragraph_before(text)
    if style is not None:
        paragraph.style = style
    if alignment is not None:
        paragraph.alignment = alignment
    if bold is not None:
        for run in paragraph.runs:
            run.bold = bold
    return paragraph


def insert_picture_before(anchor, image_path, width_points, caption, caption_style):
    paragraph = anchor.insert_paragraph_before()
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = paragraph.add_run()
    run.add_picture(str(image_path), width=Pt(width_points))

    caption_paragraph = anchor.insert_paragraph_before(caption)
    caption_paragraph.style = caption_style
    caption_paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER


def insert_page_break_before(anchor, style=None):
    paragraph = anchor.insert_paragraph_before()
    if style is not None:
        paragraph.style = style
    paragraph.add_run().add_break(WD_BREAK.PAGE)


